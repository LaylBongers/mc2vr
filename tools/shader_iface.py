#!/usr/bin/env python3
"""Check reimplemented shaders against the originals' interfaces
(docs/shaders.md).

For each entry of the registry (src/carrier/hooks/shader_reimpl.cpp:
original hash, "(shader3.bin@0x...)" in the name, mc2vr::shaders::<symbol>),
compares the generated bytecode (build/win32/generated/shaders/<symbol>.h)
with the original in the container:
  - the input and sampler declarations (dcl: usage, index, mask / type);
  - the constant table: every name with its register set, register and count;
  - the static-branch structure: the sequence of `if bN` / else / endif
    (empty else arms dropped: their placement is codegen);
  - the original's hash (the registry's key) against the container's bytes.
Reports the shadow-map taps (texld* on s15) and token counts for information.

Usage: shader_iface.py <container shader3.bin> [registry.cpp] [generated dir]
Exit 1 if any interface differs.
"""

import os
import re
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

OP_DCL, OP_IF, OP_IFC, OP_ELSE, OP_ENDIF, OP_TEXLD = 31, 40, 41, 42, 43, 66
OP_COMMENT, OP_END = 0xFFFE, 0xFFFF
REG_SAMPLER, REG_CONSTBOOL = 10, 14
SETS = {0: "b", 1: "i", 2: "c", 3: "s"}  # D3DXREGISTER_SET: BOOL, INT4, FLOAT4, SAMPLER


def fnv1a(data):
    h = 2166136261
    for b in data:
        h = ((h ^ b) * 16777619) & 0xFFFFFFFF
    return h


def reg_type(tok):
    return ((tok >> 28) & 7) | (((tok >> 11) & 3) << 3)


def words_at(buf, off):
    """The shader's tokens starting at the version token, through the end token."""
    out = []
    i = off
    first = True
    while i + 4 <= len(buf):
        t = struct.unpack_from("<I", buf, i)[0]
        out.append(t)
        if first:
            first = False
            i += 4
            continue
        op = t & 0xFFFF
        if t == 0x0000FFFF:
            return out
        n = ((t >> 16) & 0x7FFF) if op == OP_COMMENT else ((t >> 24) & 0xF)
        out.extend(struct.unpack_from("<%dI" % n, buf, i + 4))
        i += 4 * (n + 1)
    raise ValueError("no end token")


def parse_ctab(words, ci):
    """CTAB comment body (words[ci+1 ..]) -> {name: (set, reg, count)}."""
    n = (words[ci] >> 16) & 0x7FFF
    body = struct.pack("<%dI" % n, *words[ci + 1:ci + 1 + n])
    if body[:4] != b"CTAB":
        return None
    base = body[4:]
    _size, _creator, _ver, nconst, cinfo = struct.unpack_from("<5I", base, 0)
    out = {}
    for k in range(nconst):
        name_off, rset, reg, count = struct.unpack_from("<IHHH", base, cinfo + 20 * k)
        name = base[name_off:base.index(b"\0", name_off)].decode()
        out[name] = (SETS.get(rset, "?%d" % rset), reg, count)
    return out


def analyze(words):
    dcls, branches, ctab = [], [], None
    taps = 0
    i = 1
    while i < len(words):
        t = words[i]
        op = t & 0xFFFF
        if t == 0x0000FFFF:
            break
        if op == OP_COMMENT:
            n = (t >> 16) & 0x7FFF
            if ctab is None:
                ctab = parse_ctab(words, i)
            i += 1 + n
            continue
        n = (t >> 24) & 0xF
        args = words[i + 1:i + 1 + n]
        if op == OP_DCL and len(args) == 2:
            usage, dst = args
            rt = reg_type(dst)
            if rt == REG_SAMPLER:
                dcls.append("s%d:type%d" % (dst & 0x7FF, (usage >> 27) & 0xF))
            else:
                dcls.append("in:usage%d.%d:mask%x" % (usage & 0x1F, (usage >> 16) & 0xF, (dst >> 16) & 0xF))
        elif op == OP_IF and args:
            kind = "if b%d" % (args[0] & 0x7FF) if reg_type(args[0]) == REG_CONSTBOOL else "if ?"
            branches.append(kind)
        elif op == OP_IFC:
            branches.append("ifc")
        elif op == OP_ELSE:
            branches.append("else")
        elif op == OP_ENDIF:
            branches.append("endif")
        elif op == OP_TEXLD and len(args) >= 3:
            s = args[2]
            if reg_type(s) == REG_SAMPLER and (s & 0x7FF) == 15:
                taps += 1
        i += 1 + n
    return sorted(dcls), branches, ctab or {}, taps


def static_structure(branches):
    """The branch sequence without empty else arms (`else` directly followed
    by `endif`): where the compiler places those is codegen, not structure."""
    out = []
    for i, b in enumerate(branches):
        if b == "else" and i + 1 < len(branches) and branches[i + 1] == "endif":
            continue
        out.append(b)
    return out


def load_generated(path):
    text = open(path).read()
    body = text.split("{", 2)[-1]
    return [int(x, 16) for x in re.findall(r"0x([0-9a-f]{8})", body)]


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        return 2
    container = open(sys.argv[1], "rb").read()
    registry = sys.argv[2] if len(sys.argv) > 2 else os.path.join(
        ROOT, "src/carrier/hooks/shader_reimpl.cpp")
    gen = sys.argv[3] if len(sys.argv) > 3 else os.path.join(ROOT, "build/win32/generated/shaders")
    entries = re.findall(r'\{0x([0-9a-f]{8})u, "[^"]*\(shader3\.bin@(0x[0-9a-f]+)\)", mc2vr::shaders::(\w+)',
                         open(registry).read())
    if not entries:
        print("no registry entries found in", registry)
        return 2
    bad = 0
    for h, off, sym in entries:
        orig = words_at(container, int(off, 16))
        ours = load_generated(os.path.join(gen, sym + ".h"))
        problems = []
        oh = fnv1a(struct.pack("<%dI" % len(orig), *orig))
        if oh != int(h, 16):
            problems.append("registry hash %s != container's %08x at %s" % (h, oh, off))
        od, ob, oc, ot = analyze(orig)
        nd, nb, nc, nt = analyze(ours)
        if od != nd:
            problems.append("declarations differ:\n      ours %s\n      orig %s" % (nd, od))
        if oc != nc:
            diff = {k: (nc.get(k), oc.get(k)) for k in set(oc) | set(nc) if nc.get(k) != oc.get(k)}
            problems.append("constant table differs (ours, orig): %s" % diff)
        if static_structure(ob) != static_structure(nb):
            problems.append("branches differ:\n      ours %s\n      orig %s" % (" ".join(nb), " ".join(ob)))
        status = "ok " if not problems else "BAD"
        print("%s %s %-38s taps %d->%d  tokens %d->%d" % (status, h, sym, ot, nt, len(orig), len(ours)))
        for p in problems:
            print("    " + p)
        bad += bool(problems)
    print("%d of %d differ" % (bad, len(entries)))
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
